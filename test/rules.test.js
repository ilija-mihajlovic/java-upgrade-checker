const test = require('node:test')
const assert = require('node:assert/strict')
const { analyze } = require('../rules.js')

const titles = text => analyze(text).map(item => item.title)
const has = (text, title) => assert.ok(titles(text).includes(title), `expected ${title}`)

test('exports a UMD-compatible analyze function', () => assert.equal(typeof analyze, 'function'))
test('finds Spring Boot below 3', () => has('<parent><artifactId>spring-boot-starter-parent</artifactId><version>2.7.18</version></parent>', 'Spring Boot is below 3.x'))
test('accepts Spring Boot 3', () => assert.doesNotMatch(titles('<version>3.2.5</version>').join('|'), /below 3/))
test('finds old Java source and target', () => has('<maven.compiler.source>8</maven.compiler.source><maven.compiler.target>8</maven.compiler.target>', 'Java source or target is below 17'))
test('finds old Gradle toolchain', () => has('languageVersion = JavaLanguageVersion.of(11)', 'Gradle Java toolchain is below 17'))
test('finds javax and specific Jakarta namespaces', () => {
  const found = titles('import javax.persistence.Entity; import javax.servlet.Filter; import javax.validation.Valid;')
  assert.ok(found.includes('Java EE javax namespace is present'))
  assert.ok(found.includes('JPA still uses javax.persistence'))
  assert.ok(found.includes('Servlet API still uses javax.servlet'))
  assert.ok(found.includes('Validation API still uses javax.validation'))
})
test('finds Hibernate 5', () => has('hibernate-core:5.6.15.Final', 'Hibernate 5 is explicitly selected'))
test('finds removed security adapter', () => has('extends WebSecurityConfigurerAdapter', 'Removed Spring Security configuration is present'))
test('finds old Lombok', () => has('lombok:1.18.20', 'Lombok is older than Java 21 support'))
test('finds old Mockito', () => has('mockito-core:4.8.0', 'Mockito is older than the current Java 21 baseline'))
test('does not flag javax packages that stay in the JDK', () => assert.ok(!titles('import javax.sql.DataSource; import javax.crypto.Cipher;').includes('Java EE javax namespace is present')))
test('finds old Gradle wrapper', () => has('distributionUrl=https\\://services.gradle.org/distributions/gradle-7.6-bin.zip', 'Gradle wrapper is below 8.5'))
test('finds old Maven compiler plugin', () => has('<artifactId>maven-compiler-plugin</artifactId><version>3.8.1</version>', 'Maven Compiler Plugin is below 3.11'))
test('finds old Jackson override', () => has('com.fasterxml.jackson.core:jackson-databind:2.13.5', 'Jackson is older than the Spring Boot 3 line'))
test('finds JAXB after Java 8', () => has('javax.xml.bind:jaxb-api:2.3.1', 'JAXB is referenced explicitly'))
test('finds internal JDK APIs', () => has('sun.misc.Unsafe', 'JDK internal API usage is present'))
test('finds old Kotlin', () => has('kotlin_version = 1.8.22', 'Kotlin is below the JVM 21 baseline'))
test('returns an honest info result for unknown input', () => assert.equal(analyze('plugins { id "java" }')[0].severity, 'info'))
test('returns structured finding fields', () => {
  const item = analyze('<version>2.7.18</version>')[0]
  assert.deepEqual(Object.keys(item), ['severity', 'title', 'why', 'fix', 'source'])
})
